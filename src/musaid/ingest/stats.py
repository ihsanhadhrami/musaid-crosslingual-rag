"""KB statistics, written to docs/KB_STATS.md by the build."""

from collections import Counter
from statistics import median

from musaid.ingest.articles import SourceArticle
from musaid.ingest.chunking import MAX_TOKENS
from musaid.ingest.schema import (
    CATEGORY_TARGET_SHARE,
    COUNTRIES,
    COUNTRY_NAMES,
    ArticleType,
    Chunk,
    Fact,
    Mess,
    ReviewStatus,
)
from musaid.ingest.validate import KBResult

MIN_COUNTRY_TOPICS = 25  # spec §5.2


def _pct(n: int, total: int) -> str:
    return f"{n / total:.0%}" if total else "–"


def render_stats(
    sources: list[SourceArticle],
    facts: dict[str, Fact],
    result: KBResult,
    chunks: list[Chunk],
    planned: int,
) -> str:
    n = len(sources)
    metas = [s.meta for s in sources]
    status = Counter(m.status for m in metas)
    lines = [
        "# Knowledge base stats",
        "",
        "_Generated by `uv run python -m musaid.ingest.build`. Do not edit by hand._",
        "",
        "## Progress",
        "",
        "| | Count | Target |",
        "|---|---:|---|",
        f"| Planned articles (inventory.csv) | {planned} | 150–300 |",
        f"| Drafted | {n} | {planned} |",
        f"| Rewritten by hand | {status[ReviewStatus.REWRITTEN]} | all drafted |",
        f"| Facts in facts.csv | {len(facts)} | |",
        "",
        "## Articles by category",
        "",
        "| Category | Articles | Share | Target share |",
        "|---|---:|---:|---:|",
    ]
    cats = Counter(m.category for m in metas)
    for cat, target in CATEGORY_TARGET_SHARE.items():
        lines.append(f"| {cat.value} | {cats[cat]} | {_pct(cats[cat], n)} | {target:.0%} |")

    lines += ["", "## Articles by country", "", "An article can cover several countries.", ""]
    lines += ["| Country | Articles |", "|---|---:|"]
    for c in COUNTRIES:
        lines.append(f"| {COUNTRY_NAMES[c]} | {sum(c in m.countries for m in metas)} |")

    lines += ["", "## Articles by type", "", "| Type | Articles |", "|---|---:|"]
    types = Counter(m.article_type for m in metas)
    lines += [f"| {t.value} | {types[t]} |" for t in ArticleType]

    # Realistic mess
    country_topics = {t for t, cs in _topic_countries(facts).items() if len(cs - {"ALL"}) >= 2}
    used = {facts[f].topic for fids in result.facts_used.values() for f in fids}
    tags = Counter(t for m in metas for t in m.mess)
    lines += [
        "",
        "## Realistic mess",
        "",
        "| Check | Count | Target |",
        "|---|---:|---|",
        f"| Topics with per-country values in facts.csv | {len(country_topics)} "
        f"| ≥ {MIN_COUNTRY_TOPICS} |",
        f"| ...used by at least one drafted article | {len(country_topics & used)} "
        f"| {len(country_topics)} |",
        f"| Superseded articles | {sum(m.superseded_by is not None for m in metas)} | |",
        f"| Articles with cross-references | {sum(bool(v) for v in result.links.values())} | |",
    ]
    for tag in (Mess.BURIED_EXCEPTION, Mess.NEAR_DUPLICATE, Mess.COUNTRY_SPECIFIC):
        lines.append(f"| Tagged `{tag.value}` | {tags[tag]} | |")

    tokens = [c.n_tokens for c in chunks] or [0]
    lines += [
        "",
        "## Chunks",
        "",
        "| | Value |",
        "|---|---:|",
        f"| Chunks | {len(chunks)} |",
        f"| Chunks per article (mean) | {len(chunks) / max(n, 1):.1f} |",
        f"| Tokens per chunk: min / median / max "
        f"| {min(tokens)} / {median(tokens):.0f} / {max(tokens)} |",
        f"| Over {MAX_TOKENS} tokens (an unsplittable table or procedure) "
        f"| {sum(t > MAX_TOKENS for t in tokens)} |",
        f"| Under 50 tokens | {sum(c.n_tokens < 50 for c in chunks)} |",
        "",
        "## Validation",
        "",
        f"- Errors: {len(result.errors)}",
        f"- Warnings: {len(result.warnings)} (run the build to see them)",
        "",
    ]
    return "\n".join(lines)


def _topic_countries(facts: dict[str, Fact]) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for f in facts.values():
        out.setdefault(f.topic, set()).add(f.country)
    return out
