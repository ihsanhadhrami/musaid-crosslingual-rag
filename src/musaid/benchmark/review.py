"""Review sheet for the human verification pass, with an automatic competitor check.

uv run python -m musaid.benchmark.review                 # write data/eval/REVIEW.md
uv run python -m musaid.benchmark.review --unverified    # only queries not yet verified
uv run python -m musaid.benchmark.review --split test    # only test queries (verify these first)
uv run python -m musaid.benchmark.review --competitors   # print only queries with competitors

A *competitor* is a chunk that isn't gold, isn't superseded, covers the query's country,
contains every numeric critical fact, and ranks in the top 10 for the reference answer.
It may fully answer the query (then it should be gold, ANNOTATION.md §5 rule 3) or be a
hard negative (say so in notes). The sheet is a reading aid; it's not committed.
"""

import argparse
import json
import re
import sys
from pathlib import Path

from musaid.benchmark.build import ROOT, ChunkInfo, load_chunks, load_sources, norm
from musaid.benchmark.search import search

_DIGIT = re.compile(r"\d")


def competitors(
    q: dict, chunks: dict[str, ChunkInfo], k: int = 10, ratio: float = 0.75
) -> list[ChunkInfo]:
    facts = [norm(f) for f in q.get("critical_facts", []) if _DIGIT.search(f)]
    if not q.get("answerable", True) or not q.get("reference_answer"):
        return []
    gold = set(q.get("gold_chunk_ids", []))
    hits = search(chunks, q["reference_answer"], k=len(chunks), country=q.get("country"))
    best_gold = max((s for s, c in hits if c.chunk_id in gold), default=0.0)
    out = []
    for s, c in hits[:k]:
        if c.chunk_id in gold or c.superseded or s < ratio * best_gold:
            continue
        if facts and all(f in norm(c.body) for f in facts):
            out.append(c)
    return out


def _snippet(c: ChunkInfo, n: int = 160) -> str:
    return re.sub(r"\s+", " ", c.body.replace("**", ""))[:n]


def render(raws: list[dict], chunks: dict[str, ChunkInfo]) -> tuple[str, int]:
    lines = [
        "# Query review sheet",
        "",
        "Generated by `python -m musaid.benchmark.review`. For each query, check that the "
        "query sounds like a real customer, that every gold chunk fully answers it, and that "
        "the critical facts are right. Then set `verified: true` in the YAML source.",
        "",
    ]
    flagged = 0
    for q in raws:
        head = (
            f"## {q['qid']} · {q['variety']} · {q['type']} · {q.get('country') or 'no country'}"
            + (f" · {q['parallel_group']}" if q.get("parallel_group") else "")
            + ("" if q.get("verified") else " · **unverified**")
        )
        lines += [head, "", f"> {q['query']}", ""]
        if not q.get("answerable", True):
            lines += [f"Unanswerable: `{q.get('unanswerable_reason')}`", ""]
            continue
        for cid in q.get("gold_chunk_ids", []):
            c = chunks.get(cid)
            lines.append(f"- gold `{cid}` {c.title if c else '??'}: {_snippet(c) if c else ''}")
        lines += [
            f"- answer: {q.get('reference_answer', '').strip()}",
            f"- facts: {', '.join(q.get('critical_facts', [])) or '(none)'}",
        ]
        comps = competitors(q, chunks)
        if comps:
            flagged += 1
            others = "; ".join(f"`{c.chunk_id}` {c.title}" for c in comps)
            lines.append(f"- ⚠ also contains the facts: {others}")
        if q.get("notes"):
            lines.append(f"- notes: {q['notes'].strip()}")
        lines.append("")
    return "\n".join(lines) + "\n", flagged


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m musaid.benchmark.review")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--unverified", action="store_true")
    parser.add_argument("--split", choices=["dev", "test"], help="only queries in this split")
    parser.add_argument("--competitors", action="store_true", help="print flagged queries only")
    args = parser.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")

    chunks = load_chunks(args.root)
    pairs, _ = load_sources(args.root / "data" / "eval" / "source")
    raws = [r for _, r in pairs if isinstance(r, dict)]
    if args.unverified:
        raws = [r for r in raws if not r.get("verified")]
    if args.split:
        split_path = args.root / "data" / "eval" / "split.json"
        split = json.loads(split_path.read_text(encoding="utf-8")) if split_path.exists() else {}
        raws = [r for r in raws if split.get(r.get("qid")) == args.split]
    raws.sort(key=lambda r: r.get("qid", ""))

    if args.competitors:
        seen_groups = set()
        for q in raws:
            if (pg := q.get("parallel_group")) and pg in seen_groups:
                continue
            if comps := competitors(q, chunks):
                seen_groups.add(pg)
                label = pg or q["qid"]
                print(f"{label}: gold {q['gold_chunk_ids']}")
                for c in comps:
                    print(f"    + {c.chunk_id} {c.title}: {_snippet(c, 110)}")
        return 0

    text, flagged = render(raws, chunks)
    out = args.root / "data" / "eval" / "REVIEW.md"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(args.root).as_posix()}: {len(raws)} queries, {flagged} flagged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
